function build(difficulty: Difficulty, list: string[]): Puzzle[] {
  return list.map((givens, idx) => ({
    id: `${difficulty}-${idx + 1}`,
    difficulty,
    givens
  }));
}

export const PUZZLES: Record<Difficulty, Puzzle[]> = {
  easy: build("easy", EASY),
  medium: build("medium", MEDIUM),
  hard: build("hard", HARD)
};

export function randomPuzzle(difficulty: Difficulty, excludeId?: string): Puzzle {
  const pool = PUZZLES[difficulty];
  const candidates = excludeId ? pool.filter((p) => p.id !== excludeId) : pool;
  const list = candidates.length > 0 ? candidates : pool;
  return list[Math.floor(Math.random() * list.length)];
}
